// ========== INIT ==========

document.addEventListener('DOMContentLoaded', () => {
  initScrollButton();
  initPortfolioRouter();
});

// ========== SCROLL BUTTON ==========

function initScrollButton() {
  const scrollBtn = document.getElementById('scrollToTopBtn');
  if (!scrollBtn) return;

  window.addEventListener('scroll', () => {
    scrollBtn.classList.toggle('show', window.scrollY > 300);
  });

  scrollBtn.addEventListener('click', () => {
    window.scrollTo({ top: 0, behavior: 'smooth' });
  });
}

// ========== ROUTER ==========

function initPortfolioRouter() {
  const root = document.getElementById('galleryRoot');
  if (!root) return;

  window.addEventListener('hashchange', () => renderRoute(root));
  root.addEventListener('click', handleGalleryClick);
  renderRoute(root);
}

function renderRoute(root) {
  const hash = window.location.hash || '';
  const parts = hash.replace(/^#\//, '').split('/');
  const [route, param] = parts;

  if (route === 'tag' && param) {
    renderTagView(root, param);
  } else if (route === 'group' && param) {
    renderGroupView(root, param);
  } else {
    renderHomeView(root);
  }

  updateActiveCategory(hash);
}

// ========== VIEWS ==========

function renderHomeView(root) {
  root.className = 'gallery-root home-view';
  root.innerHTML = `<div class="gallery-grid">${GALLERY_BLOCKS.map(renderBlockCard).join('')}</div>`;
}

function renderTagView(root, tagId) {
  const blocks = tagId === 'all' ? GALLERY_BLOCKS : GALLERY_BLOCKS.filter(b => b.tags.includes(tagId));
  root.className = 'gallery-root tag-view';
  root.innerHTML = `<div class="gallery-grid one-column">${blocks.map(renderBlockCard).join('')}</div>`;
}

function renderGroupView(root, groupId) {
  const block = GALLERY_BLOCKS.find(b => b.id === groupId && b.type === 'group');
  if (!block) {
    root.className = 'gallery-root group-view';
    root.innerHTML = '<p>Group not found.</p>';
    return;
  }

  root.className = 'gallery-root group-view';
  root.innerHTML = `
    <h2 class="view-title">${block.title}</h2>
    <div class="gallery-grid one-column">
      ${block.images.map((img, i) => renderStageItem(img, block.title, i)).join('')}
    </div>`;

  // Preload stages only for the current group
  block.images.forEach(img => {
    const first = typeof img === 'object' ? img.stages[0] : img;
    preloadImage('images/' + first);
  });
  setTimeout(() => {
    block.images.forEach(img => {
      if (typeof img === 'object' && img.stages.length > 1) {
        img.stages.slice(1).forEach(s => preloadImage('images/' + s));
      }
    });
  }, 2000);
}

function renderStageItem(img, groupTitle, index) {
  const src = typeof img === 'object' ? img.src : img;
  const stages = typeof img === 'object' ? img.stages : [img];
  const hasMultiple = stages.length > 1;

  return `<div class="stage-wrapper${hasMultiple ? ' has-arrows' : ''}">
    <img src="images/${src}" alt="${groupTitle} ${index + 1}"
    loading="lazy"
      decoding="async"
      class="gallery-item clickable-image${hasMultiple ? ' has-stages' : ''}"
      data-stages='${JSON.stringify(stages)}'
      data-current-index='0'>
    ${hasMultiple ? `
      <button class="stage-arrow stage-arrow-left" aria-label="Previous">&#8249;</button>
      <button class="stage-arrow stage-arrow-right" aria-label="Next">&#8250;</button>
      <div class="stage-counter"><span class="stage-current">1</span> / ${stages.length}</div>
    ` : ''}
  </div>`;
}

function renderBlockCard(block) {
  const overlay = `<div class="block-overlay"><span>${block.title}</span></div>`;

if (block.type === 'group') {
  const [main, side1, side2] = block.previewImages;
  return `<article class="gallery-block group-block" data-group-id="${block.id}">
    <div class="group-layout">
      <img src="${main}" alt="${block.title}" class="gallery-item group-main" decoding="async">
      <div class="group-side">
        <img src="${side1}" alt="${block.title}" class="gallery-item" loading="lazy" decoding="async">
        <img src="${side2}" alt="${block.title}" class="gallery-item" loading="lazy" decoding="async">
      </div>
    </div>
    ${overlay}
  </article>`;
}

  return `<article class="gallery-block single-block" data-group-id="${block.id}">
    <img src="${block.previewImages[0]}" alt="${block.title}" class="gallery-item">
    ${overlay}
  </article>`;
}

// ========== CLICK HANDLER ==========

function handleGalleryClick(event) {
  const isGroupView = document.querySelector('.gallery-root.group-view') !== null;

  if (isGroupView) {
    const arrow = event.target.closest('.stage-arrow');
    if (arrow) {
      event.stopPropagation();
      const img = arrow.closest('.stage-wrapper')?.querySelector('.clickable-image');
      if (img) cycleImage(img, arrow.classList.contains('stage-arrow-right') ? 'next' : 'prev');
      return;
    }

    const img = event.target.closest('.clickable-image.has-stages');
    if (img) {
      const stages = JSON.parse(img.dataset.stages || '[]');
      if (stages.length > 1) {
        const rect = img.getBoundingClientRect();
        const ratio = (event.clientX - rect.left) / rect.width;
        if (ratio < 0.3) { cycleImage(img, 'prev'); event.stopPropagation(); }
        else if (ratio > 0.7) { cycleImage(img, 'next'); event.stopPropagation(); }
      }
      return;
    }
    return;
  }

  // Home / tag view — navigate into group
  const groupBlock = event.target.closest('.gallery-block');
  if (groupBlock?.dataset.groupId) {
    window.location.hash = `/group/${groupBlock.dataset.groupId}`;
  }
}

// ========== IMAGE CYCLING ==========

function cycleImage(img, direction) {
  const stages = JSON.parse(img.dataset.stages || '[]');
  if (stages.length < 2) return;

  const current = Number(img.dataset.currentIndex || 0);
  const next = direction === 'next'
    ? (current + 1) % stages.length
    : (current - 1 + stages.length) % stages.length;

  img.src = 'images/' + stages[next];
  img.dataset.currentIndex = String(next);

  const counter = img.closest('.stage-wrapper')?.querySelector('.stage-current');
  if (counter) counter.textContent = String(next + 1);

  // Preload neighbours
  preloadImage('images/' + stages[(next - 1 + stages.length) % stages.length]);
  preloadImage('images/' + stages[(next + 1) % stages.length]);
}

function preloadImage(src) {
  new Image().src = src;
}

// ========== ACTIVE CATEGORY ==========

function updateActiveCategory(hash) {
  const tag = hash.startsWith('#/tag/') ? hash.replace('#/tag/', '') : 'all';
  document.querySelectorAll('.category-link').forEach(link => {
    link.classList.toggle('active', link.dataset.tag === tag);
  });
}
